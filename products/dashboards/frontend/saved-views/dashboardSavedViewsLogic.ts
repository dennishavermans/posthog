import { MakeLogicType, actions, afterMount, kea, key, listeners, path, props, reducers } from 'kea'
import posthog from 'posthog-js'

import { ApiError } from 'lib/api-error'
import type { DashboardsFilters } from 'scenes/dashboard/dashboards/dashboardsLogic'

import * as api from 'products/dashboards/frontend/generated/api'
import type { DashboardSavedViewApi } from 'products/dashboards/frontend/generated/api.schemas'

export type DashboardListSavedView = Omit<DashboardSavedViewApi, 'filters'> & { filters: DashboardsFilters }
export type DashboardSavedViewScope = NonNullable<DashboardListSavedView['scope']>

export interface DashboardSavedViewsPage {
    views: DashboardListSavedView[]
    nextCursor: string | null
}

export interface DashboardSavedViewsLogicProps {
    teamId: number | null
}

